"""Generate runtime/unicode_normalization_data.inc for utf8.nfcnormalize / utf8.nfdnormalize.

Roblox exposes these two functions; standalone Luau does not. The data comes from Python's unicodedata:
the full canonical decomposition of every code point, the canonical combining classes, and the primary
composites (pairs that compose back under NFC). Hangul syllables are handled algorithmically by the runtime.

Run from the repository root after changing the Unicode version:  python scripts/gen_unicode_normalization.py
"""
import pathlib
import unicodedata

HANGUL = range(0xAC00, 0xD7A4)
OUT = pathlib.Path(__file__).resolve().parent.parent / "runtime" / "unicode_normalization_data.inc"


def main():
    decomposition, combining, composites = {}, {}, {}
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF or cp in HANGUL:
            continue
        ch = chr(cp)
        cls = unicodedata.combining(ch)
        if cls:
            combining[cp] = cls
        full = unicodedata.normalize("NFD", ch)
        if full != ch:
            decomposition[cp] = [ord(x) for x in full]
        raw = unicodedata.decomposition(ch)
        if raw and not raw.startswith("<"):
            parts = [int(x, 16) for x in raw.split()]
            if len(parts) == 2 and unicodedata.normalize("NFC", chr(parts[0]) + chr(parts[1])) == ch:
                composites[(parts[0], parts[1])] = cp

    extend, start, previous = [], None, None
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        if unicodedata.category(chr(cp)) in ("Mn", "Me", "Mc") or cp in (0x200C, 0x200D):
            if start is None:
                start = cp
            previous = cp
        elif start is not None:
            extend.append((start, previous))
            start = None
    if start is not None:
        extend.append((start, previous))

    pool, entries = [], []
    for cp, seq in sorted(decomposition.items()):
        entries.append((cp, len(pool), len(seq)))
        pool.extend(seq)

    def rows(items, width):
        lines, line = [], []
        for item in items:
            line.append(item)
            if len(line) == width:
                lines.append(", ".join(line))
                line = []
        if line:
            lines.append(", ".join(line))
        return ",\n    ".join(lines)

    text = [
        "// Generated by scripts/gen_unicode_normalization.py from Python unicodedata %s. Do not edit." % unicodedata.unidata_version,
        "struct UnicodeDecomposition { uint32_t code_point; uint32_t offset; uint32_t length; };",
        "struct UnicodeCombining { uint32_t code_point; uint32_t combining_class; };",
        "struct UnicodeComposite { uint32_t first; uint32_t second; uint32_t composite; };",
        "static const UnicodeDecomposition kUnicodeDecompositions[] = {",
        "    " + rows(["{0x%X,%d,%d}" % e for e in entries], 6),
        "};",
        "static const uint32_t kUnicodeDecompositionPool[] = {",
        "    " + rows(["0x%X" % v for v in pool], 12),
        "};",
        "static const UnicodeCombining kUnicodeCombining[] = {",
        "    " + rows(["{0x%X,%d}" % (k, v) for k, v in sorted(combining.items())], 8),
        "};",
        "static const UnicodeComposite kUnicodeComposites[] = {",
        "    " + rows(["{0x%X,0x%X,0x%X}" % (a, b, c) for (a, b), c in sorted(composites.items())], 5),
        "};",
        "struct UnicodeRange { uint32_t first; uint32_t last; };",
        "static const UnicodeRange kUnicodeGraphemeExtend[] = {",
        "    " + rows(["{0x%X,0x%X}" % r for r in extend], 6),
        "};",
        "",
    ]
    OUT.write_text("\n".join(text), encoding="ascii", newline="\n")
    print("decompositions %d, pool %d, combining %d, composites %d, extend ranges %d" % (len(entries), len(pool), len(combining), len(composites), len(extend)))


if __name__ == "__main__":
    main()
