"""Generate runtime/studio_enum_items.inc and runtime/studio_enum_specs.inc from a Studio Enum dump.

The dump is {"EnumName": [[ItemName, Value], ...], ...}, produced in Studio with Enum:GetEnums() / GetEnumItems().
Enums the runtime already implements by hand are skipped (pass their names in a text file, one per line).
Usage: python scripts/gen_studio_enums.py studio_enums.json existing_names.txt
"""
import json
import pathlib
import sys

dump = json.loads(pathlib.Path(sys.argv[1]).read_text(encoding='utf-8'))
existing = set(pathlib.Path(sys.argv[2]).read_text(encoding='utf-8').split())
runtime = pathlib.Path(__file__).resolve().parents[1] / 'runtime'
items, specs = [], []
for name in sorted(dump):
    if name in existing:
        continue
    if not dump[name]:  # an enum with no items cannot size a zero-length array
        specs.append('    {%s, nullptr, 0},' % json.dumps(name))
        continue
    rows = ',\n'.join('    {%s,%d}' % (json.dumps(i), v) for i, v in dump[name])
    items.append('static const ExportEnumEntry kStudio%sItems[] = {\n%s\n};' % (name, rows))
    specs.append('    {%s, kStudio%sItems, std::size(kStudio%sItems)},' % (json.dumps(name), name, name))
header = '// Generated by scripts/gen_studio_enums.py from Roblox Studio\'s Enum catalog. Do not edit by hand.\n'
(runtime / 'studio_enum_items.inc').write_text(header + '\n'.join(items) + '\n', encoding='utf-8', newline='\n')
(runtime / 'studio_enum_specs.inc').write_text(header + '\n'.join(specs) + '\n', encoding='utf-8', newline='\n')
print(len(specs), 'enums generated')
